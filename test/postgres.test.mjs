test('Postgres SQL keeps values parameterized, preserves literal question marks and millisecond timestamps',()=>{
 assert.equal(postgresSql("SELECT '?' AS literal WHERE id=?"),"SELECT '?' AS literal WHERE id=$1");
 assert.match(postgresSql('CREATE TABLE a (id INTEGER PRIMARY KEY AUTOINCREMENT, expires INTEGER, data BLOB)'),/BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, expires BIGINT, data BYTEA/);
 assert.equal(postgresSql('INSERT OR IGNORE INTO users(id) VALUES (?)'),'INSERT INTO users(id) VALUES ($1) ON CONFLICT DO NOTHING');
 assert.equal(postgresSql('PRAGMA wal_checkpoint(TRUNCATE)'), '');
 const c=postgresConfig({BOT_DATABASE_URL:'postgresql://test:synthetic@example.invalid:5432/test?sslmode=require',BOT_DATABASE_TUNNEL:'127.0.0.1'});
 assert.equal(c.ssl.rejectUnauthorized,true);assert.equal(c.ssl.servername,'example.invalid');assert.equal(c.host,'127.0.0.1');
});

