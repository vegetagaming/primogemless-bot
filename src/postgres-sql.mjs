// Translate only the small, fixed SQL dialect used by Store. Values stay bound parameters.
export function postgresSql(sql) {
  let text=sql.replace(/PRAGMA[^;]*(?:;|$)/gi,'').trim();
  text=text.replace(/\bBEGIN IMMEDIATE\b/gi,'BEGIN')
    .replace(/\bINTEGER PRIMARY KEY AUTOINCREMENT\b/gi,'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    .replace(/\bINTEGER\b/gi,'BIGINT').replace(/\bBLOB\b/gi,'BYTEA')
    .replace(/CASE WHEN \? THEN/gi,'CASE WHEN ? <> 0 THEN');
  if (/^INSERT OR IGNORE /i.test(text)) text=text.replace(/^INSERT OR IGNORE /i,'INSERT ')+' ON CONFLICT DO NOTHING';
  let n=0;
  // Single/double quoted literals and identifiers are never parameter placeholders.
  return text.replace(/'(?:''|[^'])*'|"(?:""|[^"])*"|\?/g,token=>token==='?'?'$'+(++n):token);
}
